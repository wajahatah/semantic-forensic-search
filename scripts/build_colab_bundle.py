"""Generate colab/sfs_bundle.py: a single paste-able Colab cell containing the tested sfs package.

The repo is private, so Colab cannot clone it. Pasting hand-copied code would drift from the tested
code; this bundle IS the tested code. Re-run after any change to src/sfs:

    python scripts/build_colab_bundle.py
"""
from __future__ import annotations

import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "colab", "sfs_bundle.py")

TEMPLATE = '''# AUTO-GENERATED by scripts/build_colab_bundle.py from src/sfs @ {commit}. DO NOT EDIT BY HAND.
# Paste this whole file into one Colab cell and run it. Re-running is safe.
import os as _os, sys as _sys

_FILES = {files}

_root = _os.environ.get("SFS_BUNDLE_ROOT", "/content/sfs_src")
for _rel, _src in _FILES.items():
    _path = _os.path.join(_root, *_rel.split("/"))
    _os.makedirs(_os.path.dirname(_path), exist_ok=True)
    with open(_path, "w", encoding="utf-8") as _f:
        _f.write(_src)
for _m in [m for m in _sys.modules if m == "sfs" or m.startswith("sfs.")]:
    del _sys.modules[_m]
if _root in _sys.path:
    _sys.path.remove(_root)
_sys.path.insert(0, _root)
print("sfs bundle installed at", _root, "| source commit {commit} | files:", len(_FILES))
'''


def collect() -> dict[str, str]:
    files = {}
    for root, _, names in os.walk(os.path.join(SRC, "sfs")):
        if "__pycache__" in root:
            continue
        for name in sorted(names):
            if name.endswith(".py"):
                path = os.path.join(root, name)
                rel = os.path.relpath(path, SRC).replace(os.sep, "/")
                with open(path, encoding="utf-8") as f:
                    files[rel] = f.read()
    return dict(sorted(files.items()))


def commit() -> str:
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "--", "src"], cwd=ROOT,
                               capture_output=True, text=True, check=True).stdout.strip()
        return sha + ("-dirty" if dirty else "")
    except Exception:
        return "unknown"


def build(out: str = OUT) -> str:
    body = "{\n" + "".join(f"    {rel!r}: {src!r},\n" for rel, src in collect().items()) + "}"
    text = TEMPLATE.format(files=body, commit=commit())
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return out


if __name__ == "__main__":
    print("wrote", build())
